"""Markdown exporter: deterministic, manifest-owned files from one snapshot.

Layout follows the levels of the preset, not graph names:

  README.md                     index: pages by level, context graphs, hashes
  top/<upper>.md                upper-ontology categories in use, with the concepts under each
  <level>/<name>.md             one page per owned graph; level from the graph's role through
                                the preset (domain, task, application), `variation/` for the
                                variation module; name = last path segment, or the first one
                                when the last only repeats the level (meta-x/domain → domain/meta-x)
  compare/concept-matrix.md     shared concept × project
  compare/variation-matrix.md   dimension × project

Rules: one snapshot per run, stable file names, sorted output, unchanged files
are not rewritten, no run timestamps, only stale files owned by the manifest
are removed, no LLM paraphrasing.
"""

from __future__ import annotations

import fnmatch
import hashlib
import json
from collections import defaultdict
from pathlib import Path

from rdflib import RDF, RDFS, SKOS, Dataset, Graph, Namespace, URIRef

from ontologizer.core.config import GUFO, KIT, Config
from ontologizer.core.levels import Preset
from ontologizer.core.route import canonical_hash

OK = Namespace(KIT)
VERSION = "0.1.0"


def _local(iri, cfg: Config) -> str:
    s = str(iri)
    if s.startswith(GUFO):
        return "gufo:" + s[len(GUFO):]
    if s.startswith(KIT):
        return s[len(KIT):]
    if s.startswith(cfg.namespace):
        return s[len(cfg.namespace):]
    return s


def _cell(text) -> str:
    return " ".join(str(text or "").split()).replace("|", "\\|")


VARIATION = "variation"


class MarkdownExporter:
    def __init__(self, cfg: Config):
        self.cfg = cfg
        self.preset = Preset.load(cfg.preset_path)
        self.warnings: list[str] = []

    # ---- layout -------------------------------------------------------------------
    def level_of(self, path: str) -> str:
        role = self.cfg.policy(path).role
        if role == VARIATION:
            return VARIATION
        levels = self.preset.graph_levels(role) if role else []
        if len(levels) != 1:
            raise ValueError(f"graph {path!r} (role {role!r}) maps to no single level of the preset")
        return levels[0]

    def page_of(self, path: str) -> str:
        level = self.level_of(path)
        segs = path.split("/")
        name = segs[0] if len(segs) > 1 and segs[-1] in (level, self.cfg.policy(path).role) else segs[-1]
        return f"{level}/{name}.md"

    @property
    def level_order(self) -> list[str]:
        return [*self.preset.level_ids, VARIATION]

    # ---- helpers ------------------------------------------------------------------
    def _label(self, g: Graph, node) -> str:
        lab = g.value(node, SKOS.prefLabel) or g.value(node, RDFS.label)
        return str(lab) if lab else _local(node, self.cfg)

    def _evidence(self, g: Graph, node) -> str:
        out = []
        for ev in sorted(g.objects(node, OK.evidence)):
            path = g.value(ev, OK.sourcePath)
            lines = g.value(ev, OK.sourceLines)
            repo = g.value(ev, OK.sourceRepo)
            commit = g.value(ev, OK.sourceCommit)
            ref = f"{repo + ':' if repo else ''}{path}{':' + str(lines) if lines else ''}"
            if commit:
                ref += f"@{str(commit)[:8]}"
            out.append(f"`{ref}`")
        return "<br>".join(out)

    # ---- per graph ----------------------------------------------------------------
    def render_graph(self, path: str, g: Graph, union: Graph) -> str:
        h = canonical_hash(g)
        lines = [f"# Graph `{path}`", "",
                 f"> Generated by ontologizer markdown exporter {VERSION} from `{self.cfg.graph_iri(path)}`, "
                 f"content hash `{h[:16]}`. Do not edit: change the graph through the write route.", ""]
        for proj in sorted(g.subjects(RDF.type, OK.Project)):
            lines += [f"**Project:** {self._label(g, proj)}"]
            if g.value(proj, OK.repository):
                lines.append(f"  · repository {g.value(proj, OK.repository)}")
            if g.value(proj, OK.analysedCommit):
                lines.append(f"  · commit `{g.value(proj, OK.analysedCommit)}`")
            if g.value(proj, SKOS.definition):
                lines += ["", str(g.value(proj, SKOS.definition))]
            lines.append("")
        concepts = sorted(g.subjects(RDF.type, OK.Concept), key=lambda c: self._label(g, c).lower())
        if concepts:
            lines += ["## Concepts", "", "| Concept | Level | gUFO | Status | Definition | Maps to | Evidence |",
                      "| --- | --- | --- | --- | --- | --- | --- |"]
            maps = defaultdict(list)
            for m in g.subjects(RDF.type, OK.Mapping):
                src = g.value(m, OK.mappingSource)
                kind = _local(g.value(m, OK.mappingKind), self.cfg)
                tgt = g.value(m, OK.mappingTarget)
                st = _local(g.value(m, OK.status), self.cfg)
                if tgt is not None:
                    txt = f"{kind} → {self._label(union, tgt)}"
                else:
                    txt = f"{kind} → *{g.value(m, OK.candidateLabel)}* (candidate)"
                if st != "hypothesis":
                    txt += f" [{st}]"
                maps[src].append(txt)
            for c in concepts:
                alts = sorted(str(a) for a in g.objects(c, SKOS.altLabel))
                name = self._label(g, c) + (f" ({', '.join(alts)})" if alts else "")
                lines.append("| " + " | ".join(_cell(x) for x in [
                    f"**{name}**",
                    _local(g.value(c, OK.level), self.cfg).removeprefix("level/"),
                    _local(g.value(c, OK.upperCategory), self.cfg),
                    _local(g.value(c, OK.status), self.cfg),
                    g.value(c, SKOS.definition),
                    "<br>".join(sorted(maps.get(c, []))),
                ]) + " | " + self._evidence(g, c) + " |")
            lines.append("")
        rels = sorted(g.subjects(RDF.type, OK.Relation))
        if rels:
            lines += ["## Relations", "", "| From | Relation | To | Status | Evidence |", "| --- | --- | --- | --- | --- |"]
            for r in rels:
                label = g.value(r, RDFS.label) or _local(g.value(r, OK.relType), self.cfg)
                lines.append("| " + " | ".join(_cell(x) for x in [
                    self._label(union, g.value(r, OK.relFrom)), label,
                    self._label(union, g.value(r, OK.relTo)), _local(g.value(r, OK.status), self.cfg),
                ]) + " | " + self._evidence(g, r) + " |")
            lines.append("")
        dims = sorted(g.subjects(RDF.type, OK.VariationDimension))
        if dims:
            lines += ["## Variation dimensions", ""]
            for d in dims:
                lines += [f"### {self._label(g, d)}", "", str(g.value(d, SKOS.definition) or ""), ""]
                for v in sorted(g.subjects(SKOS.inScheme, d), key=lambda v: self._label(g, v)):
                    lines.append(f"- **{self._label(g, v)}** — {_cell(g.value(v, SKOS.definition))}")
                lines.append("")
        choices = sorted(g.subjects(RDF.type, OK.VariationChoice))
        if choices:
            lines += ["## Variation choices", "", "| Dimension | Value | Status | Note | Evidence |",
                      "| --- | --- | --- | --- | --- |"]
            for ch in choices:
                lines.append("| " + " | ".join(_cell(x) for x in [
                    self._label(union, g.value(ch, OK.choiceDimension)),
                    self._label(union, g.value(ch, OK.choiceValue)),
                    _local(g.value(ch, OK.status), self.cfg), g.value(ch, OK.note),
                ]) + " | " + self._evidence(g, ch) + " |")
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    # ---- top level ----------------------------------------------------------------
    def render_top(self, union: Graph, owned: list[str], graphs: dict[str, Graph]) -> str:
        """Upper categories in use: each category with the owned concepts under it, by level."""
        upper = self.preset.data.get("upper", "upper")
        levels = [lv for lv in self.preset.level_ids if lv != "top"]
        by_cat: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
        for p in owned:
            g = graphs[p]
            for c in g.subjects(RDF.type, OK.Concept):
                cat = _local(g.value(c, OK.upperCategory), self.cfg)
                lv = _local(g.value(c, OK.level), self.cfg).removeprefix("level/")
                by_cat[cat][lv].append(self._label(g, c))
        lines = [f"# Top level: {upper}", "",
                 "> Generated. Upper-ontology categories the concepts below are typed with; each concept "
                 "of the domain, task and application levels sits under exactly one.", "",
                 "| Category | " + " | ".join(levels) + " | Total |", "| --- | " + " | ".join("---" for _ in levels) + " | --- |"]
        for cat in sorted(by_cat):
            counts = [len(by_cat[cat].get(lv, [])) for lv in levels]
            lines.append(f"| `{cat}` | " + " | ".join(str(n) for n in counts) + f" | {sum(counts)} |")
        lines.append("")
        for cat in sorted(by_cat):
            lines += [f"## `{cat}`", ""]
            for lv in levels:
                names = sorted(set(by_cat[cat].get(lv, [])), key=lambda n: (n.lower(), n))
                if names:
                    lines.append(f"- **{lv}:** " + ", ".join(_cell(n) for n in names))
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    # ---- cross-graph views ------------------------------------------------------
    def render_concept_matrix(self, union: Graph, projects: list) -> str:
        spaces = tuple(self.cfg.term_ns(p) for k, p in self.cfg.shared.items() if k != "variation")
        shared = [c for c in union.subjects(RDF.type, OK.Concept) if spaces and str(c).startswith(spaces)]
        rows_set = set(shared)
        cell = defaultdict(list)
        outside: dict = defaultdict(set)      # project → mapping targets that are not rows of this matrix
        for m in union.subjects(RDF.type, OK.Mapping):
            tgt = union.value(m, OK.mappingTarget)
            src = union.value(m, OK.mappingSource)
            proj = union.value(src, OK.inProject)
            if tgt is None or proj is None:
                continue
            if tgt not in rows_set:
                outside[proj].add(tgt)
            kind = _local(union.value(m, OK.mappingKind), self.cfg)
            mark = {"equivalence": "=", "specialization": "⊂", "roleOf": "role", "realization": "impl",
                    "partial": "~"}.get(kind, kind)
            cell[(tgt, proj)].append(f"{self._label(union, src)} ({mark})")
        # A project mapped onto other terms than the rows (e.g. a working graph next to a release,
        # whose terms have their own IRIs) would show an empty column without saying why.
        for p in projects:
            if outside.get(p):
                ns = sorted({str(t).rsplit(":", 1)[0] + ":" for t in outside[p]})
                self.warnings.append(
                    f"concept matrix: {self._label(union, p)} has {len(outside[p])} mapping target(s) outside "
                    f"the rows ({', '.join(ns)}); rows are the terms of `shared:` "
                    f"({', '.join(sorted(spaces))}). Put the graphs it was mapped onto in the export context "
                    f"(for a release, the project's own release graph `<path>@<ver>`).")
        names = [self._label(union, p) for p in projects]
        lines = ["# Concept × project matrix", "",
                 "> Generated. Cell: project concepts mapped to the shared concept "
                 "(= equivalence, ⊂ specialization, role, impl realization, ~ partial).", ""]
        lines += [f"> **Warning:** {w.removeprefix('concept matrix: ')}" for w in self.warnings
                  if w.startswith("concept matrix: ")]
        if any(w.startswith("concept matrix: ") for w in self.warnings):
            lines.append("")
        for level in ("domain", "task"):
            rows = sorted((c for c in shared if str(union.value(c, OK.level)).endswith("/" + level)),
                          key=lambda c: self._label(union, c).lower())
            if not rows:
                continue
            lines += [f"## {level.title()}", "", "| Concept | Status | " + " | ".join(names) + " | # |",
                      "| --- | --- | " + " | ".join("---" for _ in names) + " | --- |"]
            for c in rows:
                vals = [_cell("; ".join(sorted(cell.get((c, p), [])))) for p in projects]
                n = sum(1 for v in vals if v)
                lines.append(f"| **{_cell(self._label(union, c))}** | "
                             f"{_local(union.value(c, OK.status), self.cfg)} | " + " | ".join(vals) + f" | {n} |")
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    def render_variation_matrix(self, union: Graph, projects: list) -> str:
        dims = sorted(union.subjects(RDF.type, OK.VariationDimension), key=lambda d: self._label(union, d))
        chosen = defaultdict(list)
        for ch in union.subjects(RDF.type, OK.VariationChoice):
            p = union.value(ch, OK.choiceProject)
            d = union.value(ch, OK.choiceDimension)
            chosen[(d, p)].append(self._label(union, union.value(ch, OK.choiceValue)))
        names = [self._label(union, p) for p in projects]
        lines = ["# Variation matrix", "", "> Generated. Values chosen by each project, with evidence in the project graphs.", "",
                 "| Dimension | " + " | ".join(names) + " |", "| --- | " + " | ".join("---" for _ in names) + " |"]
        for d in dims:
            lines.append(f"| **{_cell(self._label(union, d))}** | " +
                         " | ".join(_cell("; ".join(sorted(chosen.get((d, p), [])))) for p in projects) + " |")
        return "\n".join(lines) + "\n"

    # ---- run --------------------------------------------------------------------------
    def export(self, snapshot: dict[str, str], out_dir: str | Path, patterns: list[str],
               context: list[str] = ()) -> dict:
        """Pages for graphs matching `patterns` that this config owns; views over
        those plus graphs matching `context` (read-only, no pages)."""
        match = lambda path, pats: any(fnmatch.fnmatchcase(path, pat) for pat in pats)
        self.warnings = []
        out = Path(out_dir)
        graphs: dict[str, Graph] = {}
        for iri, nt in snapshot.items():
            try:
                path = self.cfg.graph_path(iri)
            except ValueError:
                continue
            own = match(path, patterns) and not self.cfg.owned_by_other(path)
            if not own and not match(path, context):
                continue                      # not in pages, views or the index
            g = Graph()
            g.parse(data=nt, format="nt")
            graphs[path] = g
        union = Graph()
        for g in graphs.values():
            union += g
        selected = sorted(p for p in graphs if "@" not in p and match(p, patterns) and not self.cfg.owned_by_other(p))
        files: dict[str, str] = {}
        pages = {p: self.page_of(p) for p in selected}
        clash = [rel for rel in set(pages.values()) if list(pages.values()).count(rel) > 1]
        if clash:
            raise ValueError(f"several graphs export to {sorted(clash)}; rename one of them")
        for p, rel in pages.items():
            files[rel] = self.render_graph(p, graphs[p], union)
        top = f"top/{self.preset.data.get('upper', 'upper')}.md"
        files[top] = self.render_top(union, selected, graphs)
        projects = sorted(union.subjects(RDF.type, OK.Project), key=lambda p: self._label(union, p).lower())
        files["compare/concept-matrix.md"] = self.render_concept_matrix(union, projects)
        files["compare/variation-matrix.md"] = self.render_variation_matrix(union, projects)

        order = {lv: i for i, lv in enumerate(self.level_order)}
        index = ["# Ontology export", "", "> Generated by ontologizer. Pages by level; hashes identify the graph "
                 "version each page was built from.", "",
                 "## Levels", "", "| Level | Page | Graph | Triples | Hash |", "| --- | --- | --- | --- | --- |",
                 f"| top | [`{top}`]({top}) | — | — | — |"]
        for p in sorted(selected, key=lambda p: (order[self.level_of(p)], pages[p])):
            index.append(f"| {self.level_of(p)} | [`{pages[p]}`]({pages[p]}) | `{p}` | {len(graphs[p])} | "
                         f"`{canonical_hash(graphs[p])[:16]}` |")
        index += ["", "## Compare", "", "- [concept matrix](compare/concept-matrix.md): shared concept × project",
                  "- [variation matrix](compare/variation-matrix.md): dimension × project", ""]
        context = sorted(p for p in graphs if p not in selected)
        if context:
            index += ["## Context graphs", "", "Read for labels and views; exported by their owners.", "",
                      "| Graph | Triples | Hash |", "| --- | --- | --- |"]
            index += [f"| `{p}` | {len(graphs[p])} | `{canonical_hash(graphs[p])[:16]}` |" for p in context]
            index.append("")
        files["README.md"] = "\n".join(index)

        manifest_path = out / "manifest.json"
        old = json.loads(manifest_path.read_text()) if manifest_path.exists() else {"files": {}}
        manifest = {"exporter": f"markdown {VERSION}",
                    "graphs": {p: canonical_hash(graphs[p]) for p in sorted(graphs)},
                    "files": {}}
        written = 0
        for rel, text in sorted(files.items()):
            h = hashlib.sha256(text.encode()).hexdigest()
            manifest["files"][rel] = h
            target = out / rel
            if target.exists() and hashlib.sha256(target.read_bytes()).hexdigest() == h:
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
            written += 1
        removed = 0
        for rel in old.get("files", {}):
            if rel not in files and (out / rel).exists():
                (out / rel).unlink()
                removed += 1
                parent = (out / rel).parent
                while parent != out and parent.is_dir() and not any(parent.iterdir()):
                    parent.rmdir()
                    parent = parent.parent
        manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
        res = {"written": written, "removed": removed, "files": len(files)}
        if self.warnings:
            res["warnings"] = list(self.warnings)
        return res
