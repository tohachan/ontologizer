"""Generate what the visualizer container needs from this machine's owner registry.

    python -m ontologizer.adapters.visualization.deploy --hub DIR --out DIR --store-url URL

Writes `ontologizer.local.yaml` (the registry as the container sees it: `/owners/<name>`, and the
store address) and `compose.mounts.yaml` (each owner read-only, its views directory read-write).
Creates missing views directories, so that they belong to the user who runs this. Paths come from
the registry; nothing of the checkout running it is written. An owner whose views directory lies
outside its root is refused: the container could not keep the rest of the owner read-only.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

from ontologizer.core.config import _main_checkout_twin, read_hub
from ontologizer.core.views.scope import Owners

NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,63}")


def generate(hub: Path, out: Path, store_url: str) -> list[str]:
    owners = Owners(hub)
    registry, volumes, notes = {}, [], []
    for name in owners.names():
        if not NAME.fullmatch(name):
            notes.append(f"{name!r}: not a usable owner name, skipped")
            continue
        try:
            cfg = owners.config(name)
        except Exception as e:                        # an owner missing on this machine is not fatal
            notes.append(f"{name}: not available here ({type(e).__name__}), skipped")
            continue
        root = cfg.root.resolve()
        views = owners.views_dir(name)
        if not views.is_relative_to(root):
            notes.append(f"{name}: views directory {views} is outside {root}, skipped")
            continue
        views.mkdir(parents=True, exist_ok=True)
        inside = f"/owners/{name}"
        registry[name] = inside
        volumes.append(f"{root}:{inside}:ro")
        volumes.append(f"{views}:{inside}/{views.relative_to(root).as_posix()}:rw")
    out.mkdir(parents=True, exist_ok=True)
    local = {"projects": registry, "store": {"url": store_url}}
    service: dict = {"volumes": volumes}
    planner = (read_hub(hub).get("visualizer") or {}).get("planner")
    if planner:
        # The planner's settings carry no secret; its key is passed through by name from the shell
        # that runs compose, else read from the hub's .env, mounted read-only.
        local["visualizer"] = {"planner": dict(planner)}
        key_env = str(planner.get("env", "OPENROUTER_API_KEY"))
        service["environment"] = [key_env]
        env_file = next((d / ".env" for d in (hub, _main_checkout_twin(hub)) if d and (d / ".env").is_file()), None)
        if env_file:
            volumes.append(f"{env_file.resolve()}:/app/.env:ro")
        notes.append(f"planner {planner.get('adapter')!r} on; its key comes from ${key_env} or "
                     f"{env_file if env_file else 'nowhere (no .env found)'}")
    agent = (read_hub(hub).get("visualizer") or {}).get("agent")
    if agent:
        # The container's harnesses keep their sign-in in the volume at /agent-home (VISUALIZER_AGENT_HOME),
        # never in a directory of this machine.
        local.setdefault("visualizer", {})["agent"] = {k: v for k, v in dict(agent).items() if k != "home"}
        notes.append(f"agent {'on' if agent.get('enabled') is True else 'off'}; its sign-in lives in the volume "
                     "visualizer-agent-home")
    (out / "ontologizer.local.yaml").write_text(
        "# Generated by make viz-up from this machine's registry; regenerated on every run.\n"
        + yaml.safe_dump(local, sort_keys=True))
    volumes.append(f"{(out / 'ontologizer.local.yaml').resolve()}:/app/ontologizer.local.yaml:ro")
    (out / "compose.mounts.yaml").write_text(
        "# Generated by make viz-up; regenerated on every run.\n"
        + yaml.safe_dump({"services": {"visualizer": service}}, sort_keys=False))
    return notes


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--hub", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--store-url", required=True)
    a = ap.parse_args(argv)
    for note in generate(a.hub.resolve(), a.out.resolve(), a.store_url):
        print(f"viz: {note}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
